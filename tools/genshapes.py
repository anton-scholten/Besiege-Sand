#!/usr/bin/env python3
"""Writes the unit cube, cylinder and sphere the level editor's region objects use.

    python3 tools/genshapes.py Sand/Resources

These are generated rather than drawn because they are not art: a region object is a
volume the player scales, and what it needs is a clean unit shape with outward
normals. Each is centred on the origin and one unit across, so the editor's scale
handles read as the size of the region.
"""
import math
import sys


def write(path, verts, faces, name):
    out = ["# generated by tools/genshapes.py -- unit %s, centred on origin" % name]
    for v in verts:
        out.append("v %.6f %.6f %.6f" % v)
    out.append("g %s" % name)
    for f in faces:
        out.append("f %d %d %d" % (f[0] + 1, f[1] + 1, f[2] + 1))
    open(path, "w").write("\n".join(out) + "\n")
    print("wrote %s (%d verts, %d faces)" % (path, len(verts), len(faces)))


def cube():
    h = 0.5
    v = [(x * h, y * h, z * h)
         for x in (-1, 1) for y in (-1, 1) for z in (-1, 1)]
    # index bits: x*4 + y*2 + z
    q = [(0, 1, 3, 2), (4, 6, 7, 5), (0, 4, 5, 1),
         (2, 3, 7, 6), (0, 2, 6, 4), (1, 5, 7, 3)]
    f = []
    for a, b, c, d in q:
        f.append((a, b, c))
        f.append((a, c, d))
    return v, f


def cylinder(segments=24):
    # Axis along Y, not Z: this one is placed in a level rather than worn on a
    # machine, and a cylinder dropped into a level is expected to stand up. The
    # region test in SandField.Inside uses the same axis.
    h = 0.5
    v = []
    for i in range(segments):
        a = 2 * math.pi * i / segments
        x, z = math.cos(a) * h, math.sin(a) * h
        v.append((x, -h, z))
        v.append((x, h, z))
    bottom = len(v); v.append((0.0, -h, 0.0))
    top = len(v); v.append((0.0, h, 0.0))

    f = []
    for i in range(segments):
        a0, a1 = i * 2, i * 2 + 1
        b0, b1 = ((i + 1) % segments) * 2, ((i + 1) % segments) * 2 + 1
        f.append((a0, b0, b1))
        f.append((a0, b1, a1))
        f.append((bottom, b0, a0))
        f.append((top, a1, b1))
    return v, f


def sphere(rings=12, segments=20):
    r = 0.5
    v = [(0.0, 0.0, r)]
    for i in range(1, rings):
        phi = math.pi * i / rings
        for j in range(segments):
            th = 2 * math.pi * j / segments
            v.append((r * math.sin(phi) * math.cos(th),
                      r * math.sin(phi) * math.sin(th),
                      r * math.cos(phi)))
    south = len(v); v.append((0.0, 0.0, -r))

    f = []
    for j in range(segments):
        f.append((0, 1 + j, 1 + (j + 1) % segments))
    for i in range(rings - 2):
        base = 1 + i * segments
        nxt = base + segments
        for j in range(segments):
            a, b = base + j, base + (j + 1) % segments
            c, d = nxt + j, nxt + (j + 1) % segments
            f.append((a, c, d))
            f.append((a, d, b))
    last = 1 + (rings - 2) * segments
    for j in range(segments):
        f.append((south, last + (j + 1) % segments, last + j))
    return v, f


if __name__ == '__main__':
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    v, f = cube();     write(out + "/RegionBox.obj", v, f, "RegionBox")
    v, f = cylinder(); write(out + "/RegionCylinder.obj", v, f, "RegionCylinder")
    v, f = sphere();   write(out + "/RegionSphere.obj", v, f, "RegionSphere")
